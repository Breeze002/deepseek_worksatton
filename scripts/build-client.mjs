#!/usr/bin/env node
/**
 * Build the Client half into the browser module format the Web shell loads:
 * `window.__ModuleLoader__.load({ id, factory(require) { … } })`.
 *
 * `react` stays external — the shell supplies it from the browser module table — while everything
 * else is inlined, including zod, because the Remote contribution's strict codecs are live zod
 * schemas that cannot cross the wire.
 *
 *   node scripts/build-client.mjs           build once
 *   node scripts/build-client.mjs --watch   rebuild on change
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const ENTRY = resolve(root, 'src/client/index.js');
// The Web shell resolved `<package>/client` at boot; writing the built bundle to that same path
// lets the Client module loader pick the new revision up without a server restart.
const OUT = resolve(root, 'client.js');
const MODULE_ID = 'dsh-session-cards';

const wrap = (code) => `// Generated by scripts/build-client.mjs from src/client/index.js — do not edit.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(MODULE_ID)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
${code}
    return module.exports;
  },
});
`;

const emitPlugin = {
  name: 'emit-module-loader-wrapper',
  setup(build) {
    build.onEnd(async (result) => {
      if (result.errors.length > 0) return;
      const file = result.outputFiles?.[0];
      if (file === undefined) return;
      await mkdir(dirname(OUT), { recursive: true });
      await writeFile(OUT, wrap(file.text));
      console.log(`${new Date().toLocaleTimeString()} built dist/client.js — ${file.text.length} bytes`);
    });
  },
};

const options = {
  entryPoints: [ENTRY],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['es2022'],
  minify: true,
  external: ['react'],
  loader: { '.js': 'jsx' },
  write: false,
  logLevel: 'warning',
  plugins: [emitPlugin],
};

if (process.argv.includes('--watch')) {
  const context = await esbuild.context(options);
  await context.watch();
  console.log('watching src/client …');
} else {
  await esbuild.build(options);
}
